class _Lazy(Mapping[str, list[Any]]):
    """A table's columns as Python lists, converted when first read."""

    def __init__(self, table: pa.Table) -> None:
        self._table = table
        self._cache: dict[str, list[Any]] = {}

    def __getitem__(self, key: str) -> list[Any]:
        if key not in self._cache:
            self._cache[key] = self._table.column(key).to_pylist()
        return self._cache[key]

    def __iter__(self) -> Iterator[str]:
        return iter(self._table.column_names)

    def __len__(self) -> int:
        return self._table.num_columns


