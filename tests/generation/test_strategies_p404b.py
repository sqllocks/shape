def _days_cross(child: pa.Table, parent: pa.Table) -> np.ndarray[Any, Any]:
    """Days from each parent's date to the child row of the same index (the keys line up)."""
    shifted = pc.subtract(
        child["x"].combine_chunks().slice(0, len(parent)), parent["order_date"].combine_chunks()
    )
    return np.asarray(
        pc.divide(pc.cast(shifted, pa.int64()), 86_400_000_000).to_numpy(zero_copy_only=False)
    )


