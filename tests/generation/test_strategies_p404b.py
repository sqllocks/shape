class StandInDates:
    """Uniform timestamps between ``start`` and ``end`` (the ``temporal`` strategy is another work
    package; what ``derived`` adds to a date does not depend on where the date came from)."""

    name = "test_dates"

    def generate(self, spec: Mapping[str, Any], ctx: Any) -> pa.Array:
        lo = int(np.datetime64(spec["start"], "us").astype(np.int64))
        hi = int(np.datetime64(spec["end"], "us").astype(np.int64))
        u = stream(ctx, "d").uniform(ctx.row_start, ctx.n_rows)
        return pa.array(lo + (u * (hi - lo)).astype(np.int64)).cast(pa.timestamp("us"))


class StandInForeignKey:
    """A uniformly drawn key of the referenced table (``foreign_key`` is another work package)."""

    name = "foreign_key"

    def generate(self, spec: Mapping[str, Any], ctx: Any) -> pa.Array:
        table = str(spec["ref"]).split(".")[0]
        pool = ctx.engine.key_pool(table)
        u = stream(ctx, "fk").uniform(ctx.row_start, ctx.n_rows)
        return pool.take(np.minimum((u * len(pool)).astype(np.int64), len(pool) - 1))


