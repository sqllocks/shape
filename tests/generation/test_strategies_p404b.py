def test_the_comparison_can_fail(generated):
    """Negative controls: each comparison that passes above rejects a deliberate change."""

    def mutated(case_id: str, edit: Any) -> list[Any]:
        case = json.loads(json.dumps(CASES[case_id]))
        edit(case)
        result = _engine(cases_mod.schema_for(case, "shape")).generate()
        return parts.measure(case, {n: _Lazy(t) for n, t in result.tables.items()})

    def fails(case_id: str, series: list[Any]) -> bool:
        runs = FIXTURES[CASES[case_id]["strategy"]]["cases"][case_id]["runs"]
        if parts.check_series(fingerprint.fingerprint(series), [r["fingerprint"] for r in runs]):
            return True
        if CASES[case_id]["parts"]:
            got = parts.parts_fingerprint(series, CASES[case_id]["parts"], POOLS)
            return bool(parts.check_parts(got, [r["parts"] for r in runs]))
        return False

    def target(case: dict[str, Any]) -> dict[str, Any]:
        return case["tables"][case["target"][0]]["columns"][case["target"][1]]["generator"]

    assert not fails("native/first_name", generated["native/first_name"])
    # another provider's text parses into the wrong pool
    assert fails("native/first_name", generated["native/last_name"])
    assert fails("native/name", generated["native/first_name"])
    assert fails("native/email", generated["native/company_email"])
    assert fails("native/sentence", generated["native/city"])
    assert fails("native/pystr", generated["native/first_name"])
    # a formula with a 10% error, a derived column with a shifted window, a different aggregate
    assert fails(
        "formula/line_total",
        mutated(
            "formula/line_total",
            lambda c: target(c).update(expression="quantity * unit_price * 1.1"),
        ),
    )
    assert fails(
        "formula/margin",
        mutated("formula/margin", lambda c: target(c).update(expression="price - cost - 1")),
    )
    assert fails(
        "derived/add_days_uniform",
        mutated(
            "derived/add_days_uniform",
            lambda c: target(c).update(params={"distribution": "uniform", "min": 4, "max": 31}),
        ),
    )
    assert fails(
        "derived/add_days_log_normal",
        mutated(
            "derived/add_days_log_normal",
            lambda c: target(c).update(
                params={
                    "distribution": "log_normal",
                    "mean": 1.7,
                    "sigma": 0.7,
                    "min": 1,
                    "max": 60,
                }
            ),
        ),
    )
    assert fails(
        "computed/sum_children",
        mutated("computed/sum_children", lambda c: target(c).update(rule="avg_children")),
    )
    assert fails("computed/count_children", generated["computed/sum_children"])


