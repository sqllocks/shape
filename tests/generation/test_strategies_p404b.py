def _derived_engine(
    generator: dict[str, Any], source_type: str = "ts", rows: int = 2_000
) -> Engine:
    """A table with a date column ``d`` and a derived column ``x``."""
    case = cases_mod._derived({}, rule="copy")
    columns = case["tables"]["t"]["columns"]
    columns["x"] = cases_mod._col(
        "x", "timestamp", {"strategy": "derived", "source": "d", **generator}
    )
    case["tables"]["t"]["rows"] = rows
    raw = cases_mod.schema_for(case, "shape")
    if source_type == "date":
        raw["tables"]["t"]["columns"]["d"]["generator"] = {"strategy": "test_date32"}
    if source_type == "text":
        raw["tables"]["t"]["columns"]["d"]["generator"] = {"strategy": "test_text_dates"}
    engine = _engine(raw, 9)
    engine._strategies["test_date32"] = _Date32()
    engine._strategies["test_text_dates"] = _TextDates()
    return engine


class _Date32:
    def generate(self, spec: Mapping[str, Any], ctx: Any) -> pa.Array:
        return pa.array(
            19_000 + np.arange(ctx.row_start, ctx.row_start + ctx.n_rows) % 700, type=pa.int32()
        ).cast(pa.date32())


class _TextDates:
    def generate(self, spec: Mapping[str, Any], ctx: Any) -> pa.Array:
        i = np.arange(ctx.row_start, ctx.row_start + ctx.n_rows)
        forms = [
            "2024-03-%02d",
            "2024-03-%02dT10:30:00",
            "2024-03-%02d 08:15:45",
            "not a date %02d",
        ]
        return pa.array([forms[k % 4] % (1 + k % 28) for k in i])


def _days(table: pa.Table, a: str = "x", b: str = "d") -> np.ndarray[Any, Any]:
    delta = pc.subtract(table[a].combine_chunks(), table[b].combine_chunks())
    return np.asarray(pc.divide(pc.cast(delta, pa.int64()), 86_400_000_000).to_numpy())


