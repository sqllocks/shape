class _FakeFaker:
    """What the ``faker`` package offers, as far as the strategy uses it."""

    created: list[tuple[str, int | None]] = []

    def __init__(self, locale: str) -> None:
        self.locale = locale
        self._rng = np.random.default_rng(0)

    def seed_instance(self, seed: int) -> None:
        self._rng = np.random.default_rng(seed)
        _FakeFaker.created.append((self.locale, seed))

