def test_temporal_bounds_types_and_profiles(generated):
    for cid in (c for c in CASES if c.startswith("temporal/")):
        assert generated[cid].type == pa.timestamp("us"), cid
    uni = np.asarray(generated["temporal/uniform_range"].to_pylist(), dtype="datetime64[us]")
    assert uni.min() >= np.datetime64("2023-03-01") and uni.max() < np.datetime64("2024-03-01")
    # the end date is a possible day for the uniform range and the seasonal one alike (ISS-gen #10)
    assert uni.max() >= np.datetime64("2024-02-29")
    seasonal = np.asarray(generated["temporal/seasonal_dow"].to_pylist(), dtype="datetime64[us]")
    assert seasonal.max() >= np.datetime64("2025-12-31")
    assert seasonal.max() < np.datetime64("2026-01-01")
    # an hour profile gives whole seconds; none gives microseconds
    whole = np.asarray(
        generated["temporal/seasonal_both_bimodal"].to_pylist(), dtype="datetime64[us]"
    )
    assert (whole.astype("datetime64[s]") == whole).all()
    fine = np.asarray(generated["temporal/seasonal_month"].to_pylist(), dtype="datetime64[us]")
    assert (fine.astype("datetime64[s]") == fine).mean() < 0.01
    ref = np.asarray(generated["temporal/range_ref"].to_pylist(), dtype="datetime64[us]")
    assert ref.min() >= np.datetime64("2021-05-01") and ref.max() < np.datetime64("2022-05-01")
    short = np.asarray(
        generated["temporal/seasonal_short_range"].to_pylist(), dtype="datetime64[us]"
    )
    assert short.min() >= np.datetime64("2024-03-01") and short.max() < np.datetime64("2024-05-16")


def test_temporal_bimodal_hours_wrap_around_midnight(generated):
    t = np.asarray(generated["temporal/seasonal_bimodal_wrap"].to_pylist(), dtype="datetime64[us]")
    hours = ((t - t.astype("datetime64[D]")) // np.timedelta64(1, "h")).astype(int)
    share = np.bincount(hours, minlength=24) / len(hours)
    # Each peak puts about 13% of its mass on its own hour and spills into the neighbouring
    # hours, across midnight (a clipped tail would pile it on hour 23 and hour 0).
    assert 0.15 < share[[22, 3]].sum() < 0.18 and share[[23, 0, 1, 2]].min() > 0.04


def test_temporal_empty_bucket_probability_is_spread_over_the_range():
    from shape.builtins.strategies.temporal import _day_weights

    month_p = np.full(12, 1 / 12)
    dow_p = np.full(7, 1 / 7)
    first = int(np.datetime64("2024-03-01", "D").astype(np.int64))
    w = _day_weights(first, 76, month_p, dow_p)
    assert abs(w.sum() - 1.0) < 1e-12 and w[-1] < w[:-1].max() and (w > 0).all()
    # a range covering every bucket spreads nothing
    full = _day_weights(first, 800, month_p, dow_p)
    assert abs(full.sum() - 1.0) < 1e-12


