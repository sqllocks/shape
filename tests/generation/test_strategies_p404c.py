def _tables(
    parent_rows: int,
    via: dict[str, Any],
    x: dict[str, Any],
    *,
    parent: dict[str, Any] | None = None,
    child_rows: int = 50,
    extra: dict[str, Any] | None = None,
) -> Engine:
    """A parent table ``p`` (key ``pid`` 1.., column ``label``) and a child ``t`` with column
    ``via`` and ``x``."""
    col = cases_mod._col
    p_cols = {
        "pid": col("pid", "integer", {"strategy": "sequence", "start": 1}),
        "label": col("label", "string", {"strategy": "pattern", "format": "L{seq:3}"}),
        "n": col("n", "integer", {"strategy": "sequence", "start": 100, "step": 10}),
        **(parent or {}),
    }
    case = {
        "strategy": "lookup",
        "helpers": {"via": via},
        "regex": None,
        "column": col("x", "string", x),
        "tables": {"p": {"rows": parent_rows, "primary_key": ["pid"], "columns": p_cols}},
        **(extra or {}),
    }
    return Engine(schema_import.import_dump(cases_mod.schema_for(case, rows=child_rows)), seed=3)


def _enum(values: dict[str, float], **extra: Any) -> dict[str, Any]:
    return cases_mod._col(
        "via", "decimal", {"strategy": "weighted_enum", "values": values}, **extra
    )


def _lookup(source_column: str = "label", **extra: Any) -> dict[str, Any]:
    return {
        "strategy": "lookup",
        "source_table": "p",
        "source_column": source_column,
        "via": "via",
        **extra,
    }


def test_lookup_reads_the_parent_row_of_the_key():
    engine = _tables(5, _enum({"1": 1, "2": 1, "5": 1}), _lookup())
    t = engine.generate_table("t")
    keys = [int(v) for v in t["via"].to_pylist()]
    assert t["x"].to_pylist() == [f"L{k:03d}" for k in keys]
    assert {1, 2, 5} == set(keys)
    # The type of the source column is kept.
    numbers = _tables(5, _enum({"1": 1, "3": 1}), _lookup("n")).generate_table("t")
    assert numbers["x"].type == pa.int64()
    assert numbers["x"].to_pylist() == [100 + 10 * (int(k) - 1) for k in numbers["via"].to_pylist()]


def test_lookup_missing_and_null_keys_give_null():
    via = _enum({"1": 1, "9": 1}, nullable=True, null_rate=0.3)
    t = _tables(5, via, _lookup()).generate_table("t")
    for key, value in zip(t["via"].to_pylist(), t["x"].to_pylist(), strict=True):
        assert value == (None if key is None or key == 9.0 else "L001")
    assert None in t["via"].to_pylist() and 9.0 in t["via"].to_pylist()


def test_lookup_matches_integer_and_float_keys_by_value_and_text_keys():
    # float keys (a numeric weighted_enum) against an integer key column: matched by value
    t = _tables(4, _enum({"2": 1, "4": 1}), _lookup()).generate_table("t")
    assert set(t["x"].to_pylist()) == {"L002", "L004"}
    # text keys: the parent column is a pattern string, the child's via is text too
    col = cases_mod._col
    parent = {"code": col("code", "string", {"strategy": "pattern", "format": "K{seq:2}"})}
    via = col(
        "via", "string", {"strategy": "weighted_enum", "values": {"K01": 1, "K03": 1, "KZZ": 1}}
    )
    t = _tables(4, via, _lookup(key="code"), parent=parent).generate_table("t")
    got = dict(zip(t["via"].to_pylist(), t["x"].to_pylist(), strict=True))
    assert got == {"K01": "L001", "K03": "L003", "KZZ": None}


def test_lookup_takes_the_first_row_of_a_repeated_key():
    col = cases_mod._col
    parent = {"grp": col("grp", "integer", {"strategy": "weighted_enum", "values": {"7": 1}})}
    t = _tables(5, _enum({"7": 1}), _lookup(key="grp"), parent=parent).generate_table("t")
    assert set(t["x"].to_pylist()) == {"L001"}


def test_lookup_resolves_the_key_through_the_foreign_key_and_the_primary_key():
    col = cases_mod._col
    # `via` is not a column of the parent: the parent's primary key is used.
    engine = _tables(5, col("via", "integer", {"strategy": "sequence", "start": 1}), _lookup())
    assert engine.generate_table("t")["x"].to_pylist()[:5] == [
        "L001",
        "L002",
        "L003",
        "L004",
        "L005",
    ]
    # a parent without a single-column key and no `key`: a clear error
    engine = _tables(5, col("via", "integer", {"strategy": "sequence", "start": 1}), _lookup())
    engine.schema.tables["p"].primary_key = []
    with pytest.raises(ValueError, match="cannot tell which column of p"):
        engine.generate_table("t")


