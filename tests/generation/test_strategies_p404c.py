def test_record_groups_are_coherent_and_unique_is_unique(generated):
    places = {(r["city"], r["state"], r["zip"], r["lng"]) for r in cases_mod.PLACES}
    t = _engine("record_field/lng").generate_table("t")
    # anchor city, then lng from the same record
    by_city = {r["city"]: r for r in cases_mod.PLACES}
    assert all(
        by_city[c]["lng"] == v
        for c, v in zip(t["anchor"].to_pylist(), t["x"].to_pylist(), strict=True)
    )
    assert set(t["anchor"].to_pylist()) == set(by_city)
    del places
    unique = generated["record_sample/unique_all"].to_pylist()
    assert sorted(unique) == sorted(r["city"] for r in cases_mod.PLACES)
    subset = generated["record_sample/unique_subset"].to_pylist()
    assert len(subset) == len(set(subset)) == 45
    assert len(set(generated["record_sample/unique_too_many"].to_pylist())) <= 6  # with replacement
    u = _engine("record_field/unique_anchor").generate_table("t")
    states = {r["city"]: r["state"] for r in cases_mod.PLACES}
    assert [states[c] for c in u["anchor"].to_pylist()] == u["x"].to_pylist()


