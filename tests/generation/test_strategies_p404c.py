def test_lookup_index_is_built_once_per_engine():
    from shape.generation import lookup

    engine = _tables(5, _enum({"1": 1, "2": 1}), _lookup())
    a = lookup.key_index(engine, "p", "pid")
    engine.generate_table("t")
    assert lookup.key_index(engine, "p", "pid") is a
    assert a.positions(pa.array([2, 9, None], type=pa.int64())).tolist() == [1, -1, -1]
    assert a.positions(pa.array([], type=pa.int64())).tolist() == []


