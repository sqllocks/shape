@pytest.mark.parametrize("n", [1, 2, 3, 7, 60, 1000, 4097, 65_537])
def test_permutation_is_a_bijection_evaluated_row_by_row(n):
    key = (0xDEADBEEF << 64) | 12345
    whole = permute(np.arange(n), n, key)
    assert sorted(whole.tolist()) == list(range(n))
    probe = np.array([0, n - 1, n // 2], dtype=np.int64)
    assert permute(probe, n, key).tolist() == whole[probe].tolist()
    if n > 7:
        assert permute(np.arange(n), n, key + 1).tolist() != whole.tolist()
        assert whole.tolist() != list(range(n))


def test_permutation_is_well_mixed():
    n = 10_000
    p = permute(np.arange(n), n, 99)
    # first-half rows land in the first half of the range about half of the time
    assert abs((p[: n // 2] < n // 2).mean() - 0.5) < 0.03
    assert abs(np.corrcoef(np.arange(n), p)[0, 1]) < 0.05
    with pytest.raises(ValueError):
        permute(np.arange(3), 0, 1)


