from shape.generation.engine import Engine

ROOT = Path(__file__).resolve().parents[2]
BENCH = ROOT / "benchmarks" / "vs_spindle"
S1 = BENCH / "strategy_1to1"
sys.path.insert(0, str(S1))
sys.path.insert(0, str(BENCH))

import cases as cases_mod  # noqa: E402
import compare  # noqa: E402
import fingerprint  # noqa: E402

_spec = importlib.util.spec_from_file_location(
    "vs_spindle_schema_import", BENCH / "schema_import.py"
)
assert _spec and _spec.loader
schema_import = importlib.util.module_from_spec(_spec)
sys.modules["vs_spindle_schema_import"] = schema_import
_spec.loader.exec_module(schema_import)

SHAPE_SEED = 1042
STRATEGIES = ("sequence", "uuid", "weighted_enum", "distribution", "empirical", "pattern")
CASES = {k: v for k, v in cases_mod.CASES.items() if v["strategy"] in STRATEGIES}
FIXTURES = {
    s: json.loads((BENCH / "fixtures" / "strategies" / f"{s}.json").read_text("utf-8"))
    for s in STRATEGIES
}


def _engine(case_id: str, rows: int = cases_mod.ROWS, seed: int = SHAPE_SEED) -> Engine:
    raw = cases_mod.schema_for(CASES[case_id], rows=rows)
    return Engine(schema_import.import_dump(raw), seed=seed)


def _column(case_id: str, **kw: Any) -> pa.Array:
    return _engine(case_id, **kw).generate_table("t").column("x").combine_chunks()


@pytest.fixture(scope="module")
def generated() -> dict[str, pa.Array]:
    return {cid: _column(cid) for cid in CASES}


def test_fixtures_cover_every_case():
    for cid, case in CASES.items():
        fx = FIXTURES[case["strategy"]]
        assert cid in fx["cases"], cid
        assert fx["seeds"] == [43, 44, 45, 46] and fx["rows"] == cases_mod.ROWS
        assert len(fx["cases"][cid]["fingerprints"]) == 4
    assert set(STRATEGIES) == set(cases_mod.strategies())


@pytest.mark.parametrize("case_id", sorted(CASES))
def test_equivalent_to_the_baseline(case_id, generated):
    case = CASES[case_id]
    fps = FIXTURES[case["strategy"]]["cases"][case_id]["fingerprints"]
    got = fingerprint.fingerprint(generated[case_id].to_pylist())
    assert compare.check(got, fps) == []


@pytest.mark.parametrize("case_id", sorted(c for c in CASES if CASES[c]["regex"]))
def test_values_follow_the_pattern(case_id, generated):
    rx = re.compile(CASES[case_id]["regex"])
    bad = [v for v in generated[case_id].to_pylist() if v is not None and not rx.fullmatch(v)]
    assert bad == []


@pytest.mark.parametrize("case_id", sorted(CASES))
def test_identical_for_any_chunking_and_random_access(case_id):
    rows = 20_000
    engine = _engine(case_id, rows=rows)
    whole = engine.generate_table("t", chunk_rows=rows).column("x").combine_chunks()
    for chunk in (1_000, 4_093):
        parts = engine.generate_table("t", chunk_rows=chunk).column("x").combine_chunks()
        assert parts.equals(whole), f"chunk {chunk}"
    piece = engine.generate_chunk("t", 12_345, 777).column("x")
    assert piece.equals(whole.slice(12_345, 777))


@pytest.mark.parametrize("case_id", sorted(CASES))
def test_deterministic_and_seeds_differ(case_id):
    a = _column(case_id, rows=3_000)
    assert a.equals(_column(case_id, rows=3_000))
    if CASES[case_id]["strategy"] != "sequence" and not re.fullmatch(
        r"pattern/(seq_.*|unresolved_token)", case_id
    ):
        other = _column(case_id, rows=3_000, seed=SHAPE_SEED + 1)
        assert not other.equals(a)


def test_the_comparison_can_fail():
    """Negative controls: a wrong mean, a wrong weight, a wrong family and a wrong format are
    each caught by the same comparison that passes above."""

    def fails(case_id: str, mutate: dict[str, Any]) -> list[str]:
        case = json.loads(json.dumps(CASES[case_id]))
        case["column"]["generator"].update(mutate)
        raw = cases_mod.schema_for(case)
        col = (
            Engine(schema_import.import_dump(raw), seed=SHAPE_SEED)
            .generate_table("t")
            .column("x")
            .combine_chunks()
        )
        fps = FIXTURES[CASES[case_id]["strategy"]]["cases"][case_id]["fingerprints"]
        return compare.check(fingerprint.fingerprint(col.to_pylist()), fps)

    assert fails("distribution/normal", {"mean": 101})
    assert fails("distribution/normal", {"std_dev": 17})
    assert fails("distribution/poisson", {"lambda": 7.2})
    assert fails("distribution/zipf", {"alpha": 1.9})
    assert fails("weighted_enum/three", {"values": {"gold": 0.45, "silver": 0.35, "bronze": 0.2}})
    assert fails("weighted_enum/three", {"values": {"gold": 0.5, "silver": 0.3, "tin": 0.2}})
    assert fails("pattern/seq_padded", {"format": "INV-{seq:7}"})
    assert fails("pattern/random", {"format": "{random:4}-{random:3}"})
    assert fails("sequence/default", {"start": 20_000})


