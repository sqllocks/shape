def test_pattern_null_reference_gives_null():
    raw = cases_mod.schema_for(CASES["pattern/column_reference"], rows=2_000)
    raw["tables"]["t"]["columns"]["tier"]["nullable"] = True
    raw["tables"]["t"]["columns"]["tier"]["null_rate"] = 0.3
    table = Engine(schema_import.import_dump(raw), seed=9).generate_table("t")
    tier, x = table.column("tier").to_pylist(), table.column("x").to_pylist()
    assert any(t is None for t in tier)
    assert all((t is None) == (v is None) for t, v in zip(tier, x, strict=True))


@pytest.mark.parametrize(
    ("strategy", "spec", "message"),
    [
        ("weighted_enum", {}, "weighted_enum strategy requires a non-empty 'values'"),
        ("weighted_enum", {"values": {}}, "non-empty 'values'"),
        ("weighted_enum", {"values": {"a": -1, "b": 2}}, "non-negative"),
        ("weighted_enum", {"values": {"a": 0, "b": 0}}, "positive sum"),
        ("distribution", {"distribution": "no_such"}, "unknown distribution 'no_such'"),
        ("distribution", {"distribution": "uniform", "min": 5, "max": 1}, "low <= high"),
        ("distribution", {"distribution": "geometric", "p": 0}, "0 < p <= 1"),
        ("distribution", {"distribution": "zipf", "alpha": 0}, "a > 0"),
        ("distribution", {"distribution": "normal", "std_dev": -1}, "sigma >= 0"),
        ("empirical", {}, "requires 'quantiles'"),
        ("empirical", {"quantiles": {"p1": 1}}, "missing quantile keys"),
        ("pattern", {}, "requires 'format'"),
        ("pattern", {"format": ""}, "requires 'format'"),
    ],
)
def test_bad_specs_name_the_column(strategy, spec, message):
    case = {
        "strategy": strategy,
        "helpers": {},
        "regex": None,
        "column": cases_mod._col("x", "string", {"strategy": strategy, **spec}),
    }
    raw = cases_mod.schema_for(case, rows=10)
    engine = Engine(schema_import.import_dump(raw), seed=1)
    with pytest.raises(ValueError, match=re.escape(message)) as err:
        engine.generate_table("t")
    assert "t.x" in str(err.value) or message in str(err.value)
