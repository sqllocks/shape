"""P4-04a: sequence, uuid, weighted_enum, distribution, empirical and pattern.

Each case of ``benchmarks/vs_spindle/strategy_1to1/cases.py`` is generated by the engine at Shape's
fixed seed (1042) and compared, under T-21 clauses (b)-(e), with the fingerprints of the pinned
baseline's strategy at its fixed seeds 43-46 (``fixtures/strategies/*.json``, regenerated and
checked by ``baseline.py --check``). Nothing here needs the baseline's venv.
"""

