def test_distribution_families_hit_their_moments():
    n = 400_000

    def draw(name: str, **p: Any) -> np.ndarray[Any, Any]:
        generator = {"strategy": "distribution", "distribution": name, **p}
        case = {
            "strategy": "distribution",
            "helpers": {},
            "regex": None,
            "column": cases_mod._col("x", "decimal", generator),
        }
        raw = cases_mod.schema_for(case, rows=n)
        col = Engine(schema_import.import_dump(raw), seed=5).generate_table("t").column("x")
        return np.asarray(col.to_pylist())

    u = draw("uniform", min=2, max=6)
    assert abs(u.mean() - 4) < 0.02
    g = draw("geometric", p=0.25)
    assert abs(g.mean() - 4) < 0.05 and g.min() == 1
    p = draw("poisson", **{"lambda": 4})
    assert abs(p.mean() - 4) < 0.02 and abs(p.var() - 4) < 0.05
    big = draw("poisson", **{"lambda": 2500})
    assert abs(big.mean() - 2500) < 1.0 and abs(big.std() - 50) < 0.5
    par = draw("pareto", alpha=3.0, min=2)
    assert par.min() >= 2 and abs(par.mean() - 3.0) < 0.05
    assert draw("geometric", p=1.0).max() == 1
    assert draw("poisson", **{"lambda": 0}).max() == 0


def test_empirical_follows_its_quantiles(generated):
    col = np.asarray(generated["empirical/linear"].to_pylist())
    q = cases_mod._QUANTILES
    got = np.quantile(col, [0.1, 0.25, 0.5, 0.75, 0.9])
    want = [q["p10"], q["p25"], q["p50"], q["p75"], q["p90"]]
    assert np.allclose(got, want, rtol=0.03)
    assert col.min() >= q["p1"] and col.max() <= q["p99"]
    anchored = np.asarray(generated["empirical/tail_anchors"].to_pylist())
    assert anchored.min() < q["p1"] and anchored.max() > q["p99"]


def test_empirical_cubic_without_scipy_falls_back_to_linear(monkeypatch):
    case = json.loads(json.dumps(CASES["empirical/linear"]))
    case["column"]["generator"]["interpolation"] = "cubic"
    raw = cases_mod.schema_for(case, rows=500)
    monkeypatch.setitem(sys.modules, "scipy", None)
    monkeypatch.setitem(sys.modules, "scipy.interpolate", None)
    with warnings.catch_warnings(record=True) as caught:
        warnings.simplefilter("always")
        cubic = Engine(schema_import.import_dump(raw), seed=3).generate_table("t").column("x")
    assert any(issubclass(w.category, ImportWarning) for w in caught)
    linear = _column("empirical/linear", rows=500, seed=3)
    assert cubic.combine_chunks().equals(linear)


