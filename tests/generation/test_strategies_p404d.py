def test_the_comparison_can_fail():
    """Negative controls: each wrong setting is caught by the comparison that passes above."""

    def fails(case_id: str, mutate: dict[str, Any], table: str, column: str) -> list[str]:
        case = json.loads(json.dumps(rc.CASES[case_id]))
        case["tables"][table]["columns"][column]["generator"].update(mutate)
        return _fails(case_id, _lists(_engine(case).generate().tables))

    assert fails("foreign_key/uniform", {"distribution": "zipf", "alpha": 1.2}, "c", "x")
    assert fails("foreign_key/zipf_top_level_alpha", {"alpha": 1.5}, "c", "x")
    assert fails("foreign_key/zipf_top_level_alpha", {"distribution": "pareto"}, "c", "x")
    assert fails("foreign_key/pareto_capped", {"max_per_parent": 80}, "c", "x")
    assert fails("foreign_key/pareto", {"alpha": 2.0}, "c", "x")
    assert fails("foreign_key/nullable", {}, "c", "x") == []
    assert fails("foreign_key/self_reference", {"distribution": "uniform"}, "e", "mgr") == []
    assert fails("composite_foreign_key/zipf", {"params": {"alpha": 2.0}}, "ret", "a")
    assert fails("composite_foreign_key/uniform", {"distribution": "zipf"}, "ret", "a")
    assert fails(
        "lifecycle/three_phases",
        {"phases": {"introduced": 0.2, "active": 0.65, "discontinued": 0.15}},
        "t",
        "x",
    )
    assert fails(
        "lifecycle/three_phases",
        {"phases": {"introduced": 0.1, "active": 0.75, "retired": 0.15}},
        "t",
        "x",
    )
    assert fails("self_referencing/levels3_roots8", {"levels": 4}, "cat", "parent_category_id")
    assert fails("self_referencing/levels3_roots8", {"root_count": 40}, "cat", "parent_category_id")
    assert fails("scd2/default_gap", {"min_gap_days": 30}, "dim", "effective_date")
    assert fails("scd2/default_gap", {"role": "is_current"}, "dim", "end_date")


