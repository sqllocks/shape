def _tables_under(
    kernel: str, monkeypatch: pytest.MonkeyPatch, case: dict[str, Any]
) -> dict[str, pa.Table]:
    monkeypatch.setenv("SHAPE_KERNEL", kernel)
    dispatch.reset()
    try:
        return _engine(case).generate().tables
    finally:
        monkeypatch.undo()
        dispatch.reset()


