def _fails(case_id: str, tables: dict[str, dict[str, list[Any]]]) -> list[str]:
    case = rc.CASES[case_id]
    fx = FIXTURES[case["strategy"]]["cases"][case_id]["observations"]
    out: list[str] = []
    for name, values in rc.observe(case, tables).items():
        out += [f"{name}: {m}" for m in rcmp.check(name, fingerprint.fingerprint(values), fx[name])]
    return out


