def test_foreign_key_zipf_truncated_to_the_pool_has_the_right_shape():
    from shape.builtins.strategies._relational import ZIPF_HEAD, zipf_index

    u = (np.arange(400_000) + 0.5) / 400_000
    for pool, alpha in ((50, 1.2), (3_000, 1.5), (ZIPF_HEAD, 1.1)):
        idx = zipf_index(u, pool, alpha)
        assert idx.min() == 0 and idx.max() <= pool - 1
        weights = np.arange(1, pool + 1, dtype=np.float64) ** (-alpha)
        want = (weights / weights.sum())[:5]
        got = np.bincount(idx, minlength=5)[:5] / len(u)
        assert np.allclose(got, want, rtol=0.02, atol=1e-4), (pool, alpha, got, want)
    # a pool beyond the exact table: its tail is integrated, and its mass must match the power law
    for pool, alpha in ((3_000_000, 1.2), (3_000_000, 1.0), (50_000_000, 0.8)):
        idx = zipf_index(u, pool, alpha)
        assert idx.min() == 0 and idx.max() <= pool - 1
        low, high = ZIPF_HEAD + 0.5, pool + 0.5
        exact = (np.arange(1, ZIPF_HEAD + 1, dtype=np.float64) ** (-alpha)).sum()
        tail = (
            np.log(high / low)
            if alpha == 1.0
            else (low ** (1 - alpha) - high ** (1 - alpha)) / (alpha - 1)
        )
        assert abs((idx >= ZIPF_HEAD).mean() - tail / (exact + tail)) < 0.002, (pool, alpha)


def test_foreign_key_constrained_without_address_is_null_or_any_parent():
    for nullable in (True, False):
        cust = _t(50, ["cid"], cid=_col("cid", "sequence"))
        addr = _t(
            10,
            ["aid"],
            aid=_col("aid", "sequence"),
            cid=_col("cid", "foreign_key", ref="cust.cid"),
        )
        order = rc.base._col(
            "aid",
            "integer",
            {"strategy": "foreign_key", "ref": "addr.aid", "constrained_by": "cid"},
            nullable=nullable,
        )
        child = _t(
            2_000,
            ["oid"],
            oid=_col("oid", "sequence"),
            cid=_col("cid", "foreign_key", ref="cust.cid"),
            aid=order,
        )
        tables = _lists(
            _engine(_case({"cust": cust, "addr": addr, "ord": child})).generate().tables
        )
        owner = dict(zip(tables["addr"]["aid"], tables["addr"]["cid"], strict=True))
        has = set(owner.values())
        for aid, cid in zip(tables["ord"]["aid"], tables["ord"]["cid"], strict=True):
            if cid in has:
                assert owner[aid] == cid
            elif nullable:
                assert aid is None
            else:
                assert aid in owner


