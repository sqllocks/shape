@pytest.mark.parametrize("case_id", sorted(rc.CASES))
def test_identical_for_any_chunking_and_random_access(case_id):
    case = json.loads(json.dumps(rc.CASES[case_id]))
    for spec in case["tables"].values():
        spec["rows"] = min(spec["rows"], 12_000) if spec["rows"] > 400 else spec["rows"]
    engine = _engine(case)
    for name, spec in case["tables"].items():
        rows = spec["rows"]
        whole = engine.generate_table(name, chunk_rows=rows)
        for chunk in (1_000, 4_093):
            assert engine.generate_table(name, chunk_rows=chunk).equals(whole), (name, chunk)
        lo = rows // 3
        piece = engine.generate_chunk(name, lo, min(777, rows - lo))
        assert pa.Table.from_batches([piece]).equals(whole.slice(lo, piece.num_rows)), name
    # a fresh engine reading the last chunk first (cold caches) gives the same rows
    fresh = _engine(case)
    name = next(reversed(case["tables"]))
    rows = case["tables"][name]["rows"]
    tail = fresh.generate_chunk(name, max(rows - 500, 0), min(500, rows))
    assert pa.Table.from_batches([tail]).equals(
        engine.generate_table(name, chunk_rows=rows).slice(max(rows - 500, 0), tail.num_rows)
    )


