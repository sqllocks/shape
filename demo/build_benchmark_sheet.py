"""Build demo/BENCHMARKS.md from the committed product measurements (no number typed by hand).

    python demo/build_benchmark_sheet.py          # rewrite demo/BENCHMARKS.md
    python demo/build_benchmark_sheet.py --check  # exit 1 if the file is out of date

Source: benchmarks/baselines/2026-09-30-product/product_bench.json, written by
benchmarks/measure_product.py (decision DM-2). Values are truncated, never rounded up.
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
SRC = REPO / "benchmarks" / "baselines" / "2026-09-30-product" / "product_bench.json"
OUT = REPO / "demo" / "BENCHMARKS.md"

ROWS = [
    ("d1.parquet", "D1, 200k rows x 6 columns, Parquet"),
    ("d2.parquet", "D2, 1M rows x 20 columns, Parquet"),
    ("d2.csv", "D2, 1M rows x 20 columns, CSV"),
    ("d3.parquet", "D3, 5M rows x 10 columns, Parquet"),
    ("d4.parquet", "D4, 100k rows x 200 columns, Parquet"),
]


def trunc(x: float, nd: int = 2) -> str:
    """Truncate (never round up) to nd decimals."""
    f = 10**nd
    return f"{math.floor(x * f) / f:.{nd}f}"


def trunc_int(x: float) -> str:
    return f"{math.floor(x):,}"


def build() -> str:
    d = json.loads(SRC.read_text())
    meta, su = d["_meta"], d["startup"]
    lines = [
        "# Benchmark sheet",
        "",
        "<!-- Generated by demo/build_benchmark_sheet.py from "
        "benchmarks/baselines/2026-09-30-product/. Do not edit by hand. -->",
        "",
        "Every number below comes from one committed file, "
        "`benchmarks/baselines/2026-09-30-product/product_bench.json` (decision DM-2). Nothing is "
        "extrapolated, and every value is truncated, never rounded up. **These were not measured "
        "in Fabric**: live Fabric timings go in [`LIVE_TIMINGS.md`](LIVE_TIMINGS.md) after the "
        "owner's dry run.",
        "",
        "## What was measured",
        "",
        f"- Machine: {meta['cores']} cores, `{meta['platform']}`, Python {meta['python']}, "
        f"started {meta['started']}.",
        "- What ran: `shape.profile` itself, exact mode (the released behaviour), on the "
        "deterministic profiling datasets, written by `benchmarks/measure_product.py`.",
        f"- Each timing is the median of {meta['runs']} runs, each in a fresh process. Wall-clock "
        "excludes `import shape`. Peak memory is the process's peak resident set size.",
        "- Before any timing counts, the row count must match the file and the profile output "
        "must be identical across the runs (hash compared). Both held for every row below.",
        "",
        "## Profiling: wall-clock, throughput and peak memory",
        "",
        "| Dataset | Wall-clock s | Rows per second | Peak memory MB |",
        "|---|---:|---:|---:|",
    ]
    for key, label in ROWS:
        r = d["profile"][key]
        assert r["output_identical_across_runs"], key
        lines.append(
            f"| {label} | {trunc(r['median_s'])} | {trunc_int(r['rows_per_s'])} | "
            f"{trunc_int(r['peak_rss_mb'])} |"
        )
    lines += [
        "",
        "Rows per second is rows divided by the median wall-clock, truncated to a whole number.",
        "Wide tables are slower per row: D4 has 200 columns.",
        "",
        "## Start-up",
        "",
        f"Median of {su['runs']} fresh processes.",
        "",
        "| What | Wall-clock ms |",
        "|---|---:|",
        "| `python -c pass` (the interpreter alone) | "
        f"{trunc_int(su['python_bare_median_s'] * 1000)} |",
        f'| `python -c "import shape"` | {trunc_int(su["import_shape_median_s"] * 1000)} |',
        f"| `shape version` (the CLI) | {trunc_int(su['cli_version_cmd_median_s'] * 1000)} |",
        "",
        "## Not measured",
        "",
        "Bounded (sketch) mode and the Rust engine are being built, so nothing here measures "
        "them: no speed and no memory number exists for either. Fabric timings are in "
        "`LIVE_TIMINGS.md` only once filled in.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    text = build()
    if a.check:
        if not OUT.exists() or OUT.read_text() != text:
            print("demo/BENCHMARKS.md is out of date", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
