"""Build demo/BENCHMARKS.md from the committed baselines (no number is typed by hand).

    python demo/build_benchmark_sheet.py          # rewrite demo/BENCHMARKS.md
    python demo/build_benchmark_sheet.py --check  # exit 1 if the file is out of date

Sources: benchmarks/baselines/2026-09-29/profile_bench.json, retail_bench.json and the
equivalence verifier outputs next to them (plan section 12.4, decision DM-2).
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
BASE = REPO / "benchmarks" / "baselines" / "2026-09-29"
OUT = REPO / "demo" / "BENCHMARKS.md"

PROFILE_ROWS = [
    ("d1.parquet", "D1, 200k rows x 6 columns, Parquet"),
    ("d2.parquet", "D2, 1M rows x 20 columns, Parquet"),
    ("d2.csv", "D2, 1M rows x 20 columns, CSV"),
    ("d3.parquet", "D3, 5M rows x 10 columns, Parquet"),
    ("d4.parquet", "D4, 100k rows x 200 columns, Parquet"),
    ("mt", "MT, 3 tables (20k / 800 / 200k rows) with foreign-key detection"),
]


def _equivalent(name: str) -> str:
    line = next(
        ln for ln in (BASE / name).read_text().splitlines() if ln.startswith("COLUMNS EQUIVALENT")
    )
    return line.split(":", 1)[1].strip()


def build() -> str:
    prof = json.loads((BASE / "profile_bench.json").read_text())
    retail = json.loads((BASE / "retail_bench.json").read_text())
    meta, env = prof["_meta"], retail["env"]
    lines = [
        "# Benchmark sheet",
        "",
        "<!-- Generated by demo/build_benchmark_sheet.py from benchmarks/baselines/2026-09-29/. "
        "Do not edit by hand. -->",
        "",
        "Every number below comes from a committed file under "
        "`benchmarks/baselines/2026-09-29/` (decision DM-2). Nothing is extrapolated. "
        "**These were not measured in Fabric**: live Fabric timings go in "
        "[`LIVE_TIMINGS.md`](LIVE_TIMINGS.md) after the owner's dry run.",
        "",
        "## What was measured",
        "",
        f"- Machine: {meta['cores']} cores, {meta['cpu']}, `{meta['platform']}`, "
        f"Python {env['python']}.",
        "- Each timing is the median of 5 runs (profiling) or 3 runs (retail), in a fresh process "
        "per run, runs interleaved between tools.",
        "- The profiling numbers time the benchmark port `benchmarks/profile_1to1/port.py`, the "
        "vectorised numpy + pyarrow profiler that `shape.profile` was ported from. They were "
        "**not** measured on `shape.profile` itself. In the profiling table, `port MT` is the "
        "port's default threading (4 cores) and `port 1T` is one thread.",
        "- Equivalence comes first: the same port output matches the reference profiler "
        "field by field on every dataset before its timing counts.",
        "",
        "## Profiling: Spindle profiler vs vectorised port",
        "",
        f"Source: `profile_bench.json` (machine: {meta['cores']} cores, "
        f"started {meta['started']}); "
        "equivalence: `profile_verify.txt` (every field bitwise-identical on the datasets "
        "listed below).",
        "",
        "| Dataset | Spindle 3.0.1 s | port MT s | port 1T s | speedup MT | speedup 1T |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for key, label in PROFILE_ROWS:
        r = prof[key]
        s, m, o = (r[k]["median_s"] for k in ("spindle", "port-mt", "port-st"))
        lines.append(f"| {label} | {s:.2f} | {m:.2f} | {o:.2f} | {s / m:.1f}x | {s / o:.1f}x |")
    lines += [
        "",
        "## Retail data generation: Spindle vs vectorised port",
        "",
        f"Source: `retail_bench.json` (machine: {env['cpu_count']} cores, seed {retail['seed']}, "
        f"median of {retail['runs']} runs, generate plus write Parquet). Equivalence: "
        f"`retail_verify_medium.txt` and `retail_verify_large.txt` "
        f"(columns equivalent: medium {_equivalent('retail_verify_medium.txt')}, "
        f"large {_equivalent('retail_verify_large.txt')}). The port runs with a different seed "
        "from Spindle, so the outputs are statistically equivalent within the verifier's "
        "tolerances, not bit-identical.",
        "",
        "| Scale | Rows | Spindle 3.0.1 s | port s | speedup | peak RSS MB (Spindle / port) |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for scale, v in retail["scales"].items():
        s, p = v["summary"]["spindle"], v["summary"]["port"]
        lines.append(
            f"| {scale} | {s['rows']:,} | {s['total_s']:.2f} | {p['total_s']:.2f} | "
            f"{s['total_s'] / p['total_s']:.1f}x | "
            f"{s['peak_rss_mb']:.0f} / {p['peak_rss_mb']:.0f} |"
        )
    lines += [
        "",
        "Data generation is not part of the early-access product (profiling only); this table "
        "is the equivalence-verified retail port that produces the demo data.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    text = build()
    if a.check:
        if not OUT.exists() or OUT.read_text() != text:
            print("demo/BENCHMARKS.md is out of date", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
