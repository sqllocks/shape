"""Row counts equal the baseline's, for every domain at every scale (P6-01e).

    source scripts/env.sh
    "$SHAPE_VENV/bin/python" benchmarks/vs_spindle/domain_1to1/rowcounts.py   # both sides, compare
    "$SPINDLE_PY" benchmarks/vs_spindle/domain_1to1/rowcounts.py baseline --out A.json
    "$SHAPE_VENV/bin/python" benchmarks/vs_spindle/domain_1to1/rowcounts.py shape --out B.json
    "$SHAPE_VENV/bin/python" benchmarks/vs_spindle/domain_1to1/rowcounts.py compare A.json B.json

Two kinds of count, for each of the 14 domains in both modes (3nf, star) and for every composite
in ``composites.py``:

* **planned**: the rows each table gets at *every* scale preset the schema has (`fabric_demo` to
  `xxxl`, 3.7 x 10^10 rows in the largest): the baseline's ``calculate_row_counts`` against
  Shape's ``Engine.row_counts``. Nothing is generated. (The baseline's planner also returns one
  working value that is not a table, ``daily_price_years``; only tables are compared.)
* **generated**: the rows of the tables the two tools really produce, at the scales named by
  ``--generate-scales`` (default ``fabric_demo,demo,small``: the ones that run in seconds). The
  larger scales are generated by ``verify.py`` (clause (a)) at small and medium.

``compare`` exits 1 on any difference: a table missing on either side, a scale missing, a count
that differs. There is no allow-list: every count is equal.

Before the real comparison a **negative control** runs the comparator on copies of the baseline's
counts with a fault put in (a count raised by one, a table, a scale and a schema dropped) and
requires it to report every one of them (and to report nothing for identical inputs); if it
misses one the harness itself is broken: it exits 3 and compares nothing.

Exit codes: 0 equal, 1 a difference, 2 an input is missing, 3 the negative control failed.
"""

from __future__ import annotations

import argparse
import copy
import json
import subprocess
import sys
import time
from pathlib import Path
from typing import Any

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
sys.path.insert(0, str(HERE))
import composites  # noqa: E402
from paths import BENCH_OUT_DIR, SHAPE_PY, SPINDLE_PY, SPINDLE_ROOT  # noqa: E402

MODES = ("3nf", "star")
SEED = 42
DEFAULT_GENERATE = "fabric_demo,demo,small"
# key -> {"planned": {scale: {table: rows}}, "generated": {scale: {table: rows}}}
Counts = dict[str, dict[str, dict[str, dict[str, int]]]]


def keys(domains: list[str]) -> list[tuple[str, str, str | None]]:
    """``(key, domain-or-spec, mode)`` for every schema covered: the domains in both modes, then
    the composites. Each side lists its own domains, so a domain missing on one side is a
    difference."""
    out: list[tuple[str, str, str | None]] = [(f"{d}_{m}", d, m) for d in domains for m in MODES]
    out += [(composites.harness_id(s), s, None) for s in composites.specs()]
    return out


# ---- the baseline side (Spindle venv) -------------------------------------------------------


def baseline_counts(generate_scales: list[str]) -> Counts:
    sys.path.insert(0, str(SPINDLE_ROOT))
    import dump_schema
    from sqllocks_spindle.cli import _resolve_domain
    from sqllocks_spindle.engine.generator import Spindle, calculate_row_counts

    out: Counts = {}
    for key, name, mode in keys(dump_schema.domain_names()):
        domain = composites.baseline_domain(name) if mode is None else _resolve_domain(name, mode)
        schema = domain.get_schema()
        planned: dict[str, dict[str, int]] = {}
        for scale in schema.generation.scales:
            schema.generation.scale = scale
            counts = calculate_row_counts(schema)
            # ``calculate_row_counts`` also returns a working value that is not a table
            # (``daily_price_years``, the years a ``per_year`` count multiplies): only tables count.
            planned[scale] = {k: int(v) for k, v in counts.items() if k in schema.tables}
        generated: dict[str, dict[str, int]] = {}
        for scale in generate_scales:
            if scale in planned:
                res = Spindle().generate(domain=domain, scale=scale, seed=SEED)
                generated[scale] = {t: len(df) for t, df in res.tables.items()}
        out[key] = {"planned": planned, "generated": generated}
        print(
            f"baseline {key}: {len(planned)} scales planned, {len(generated)} generated", flush=True
        )
    return out


# ---- Shape's side (Shape venv) --------------------------------------------------------------


def shape_counts(generate_scales: list[str]) -> Counts:
    from shape.generation.composite import resolve
    from shape.generation.domains import domain_names, load_domain
    from shape.generation.engine import Engine

    out: Counts = {}
    for key, name, mode in keys(sorted(domain_names())):
        schema = resolve(name).schema if mode is None else load_domain(name, mode=mode).schema
        planned: dict[str, dict[str, int]] = {}
        for scale in schema.generation.scales:
            engine = Engine(schema, scale=scale, seed=SEED)
            planned[scale] = {t: int(engine.row_counts[t]) for t in engine.order}
        generated: dict[str, dict[str, int]] = {}
        for scale in generate_scales:
            if scale in planned:
                tables = Engine(schema, scale=scale, seed=SEED).generate().tables
                generated[scale] = {t: int(tbl.num_rows) for t, tbl in tables.items()}
        out[key] = {"planned": planned, "generated": generated}
        print(
            f"shape    {key}: {len(planned)} scales planned, {len(generated)} generated", flush=True
        )
    return out


# ---- comparison -----------------------------------------------------------------------------


def compare(baseline: Counts, shape: Counts) -> list[str]:
    """Every difference, as a line of text (empty when the counts are equal)."""
    diffs: list[str] = []
    for key in sorted(baseline.keys() | shape.keys()):
        if key not in baseline or key not in shape:
            diffs.append(f"{key}: only in {'baseline' if key in baseline else 'shape'}")
            continue
        for kind in ("planned", "generated"):
            b, s = baseline[key][kind], shape[key][kind]
            for scale in sorted(b.keys() | s.keys()):
                if scale not in b or scale not in s:
                    side = "baseline" if scale in b else "shape"
                    diffs.append(f"{key} {kind} {scale}: scale only in {side}")
                    continue
                for table in sorted(b[scale].keys() | s[scale].keys()):
                    x, y = b[scale].get(table), s[scale].get(table)
                    if x != y:
                        diffs.append(f"{key} {kind} {scale} {table}: baseline {x} shape {y}")
    return diffs


def negative_control(baseline: Counts) -> list[str]:
    """Faults the comparator must catch; returns the ones it missed."""
    missed: list[str] = []
    key = sorted(baseline)[0]
    kind = "planned"
    scale = sorted(baseline[key][kind])[0]
    table = sorted(baseline[key][kind][scale])[0]

    def mutated(change: Any) -> Counts:
        copy_ = copy.deepcopy(baseline)
        change(copy_)
        return copy_

    faults = {
        "a count raised by one": lambda c: c[key][kind][scale].__setitem__(
            table, c[key][kind][scale][table] + 1
        ),
        "a table dropped": lambda c: c[key][kind][scale].pop(table),
        "a scale dropped": lambda c: c[key][kind].pop(scale),
        "a schema dropped": lambda c: c.pop(key),
    }
    for label, change in faults.items():
        if not compare(baseline, mutated(change)):
            missed.append(label)
    gen_key = next((k for k in sorted(baseline) if baseline[k]["generated"]), None)
    if gen_key is not None:
        gscale = sorted(baseline[gen_key]["generated"])[0]
        gtable = sorted(baseline[gen_key]["generated"][gscale])[0]

        def bump(c: Counts) -> None:
            c[gen_key]["generated"][gscale][gtable] += 1

        if not compare(baseline, mutated(bump)):
            missed.append("a generated count raised by one")
    if compare(baseline, copy.deepcopy(baseline)):
        missed.append("identical inputs reported as different")
    return missed


def check(baseline: Counts, shape: Counts, *, quiet: bool = False) -> int:
    missed = negative_control(baseline)
    if missed:
        print("negative control FAILED: the comparator missed: " + "; ".join(missed))
        return 3
    print(
        "negative control: the comparator finds a raised count, a dropped table, scale and schema"
    )
    diffs = compare(baseline, shape)
    planned = sum(len(v["planned"]) * 1 for v in baseline.values())
    generated = sum(len(v["generated"]) for v in baseline.values())
    cells = sum(
        len(tables)
        for v in baseline.values()
        for kind in ("planned", "generated")
        for tables in v[kind].values()
    )
    print(
        f"{len(baseline)} schemas, {planned} planned scales, {generated} generated scales, "
        f"{cells} table counts compared"
    )
    if diffs:
        if not quiet:
            for line in diffs[:200]:
                print("DIFF " + line)
        print(f"{len(diffs)} differences: NOT equal")
        return 1
    print("row counts equal the baseline's in every cell")
    return 0


# ---- driver ---------------------------------------------------------------------------------


def _read(path: Path) -> Counts:
    data: Counts = json.loads(path.read_text("utf-8"))
    return data


def _side(python: Path, side: str, out: Path, scales: str) -> bool:
    cmd = [str(python), str(Path(__file__)), side, "--out", str(out), "--generate-scales", scales]
    return subprocess.run(cmd).returncode == 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument(
        "what", nargs="?", default="run", choices=["run", "baseline", "shape", "compare"]
    )
    ap.add_argument("files", nargs="*", help="compare: BASELINE.json SHAPE.json")
    ap.add_argument("--out", help="baseline/shape: where to write the counts")
    ap.add_argument("--generate-scales", default=DEFAULT_GENERATE)
    ap.add_argument("--report", help="run/compare: write the verdict as JSON")
    a = ap.parse_args(argv)
    scales = [s for s in a.generate_scales.split(",") if s]
    started = time.time()
    if a.what in ("baseline", "shape"):
        counts = baseline_counts(scales) if a.what == "baseline" else shape_counts(scales)
        out = Path(a.out or BENCH_OUT_DIR / "rowcounts" / f"{a.what}.json")
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(json.dumps(counts, indent=1, sort_keys=True) + "\n")
        print(f"wrote {out}")
        return 0
    if a.what == "compare":
        if len(a.files) != 2:
            ap.error("compare takes BASELINE.json SHAPE.json")
        paths = [Path(f) for f in a.files]
    else:
        folder = BENCH_OUT_DIR / "rowcounts"
        paths = [folder / "baseline.json", folder / "shape.json"]
        for side, python, path in (
            ("baseline", SPINDLE_PY, paths[0]),
            ("shape", SHAPE_PY, paths[1]),
        ):
            if not _side(python, side, path, a.generate_scales):
                print(f"the {side} side failed", file=sys.stderr)
                return 2
    for p in paths:
        if not p.is_file():
            print(f"missing: {p}", file=sys.stderr)
            return 2
    baseline, shape = _read(paths[0]), _read(paths[1])
    code = check(baseline, shape)
    if a.report:
        Path(a.report).write_text(
            json.dumps(
                {
                    "exit": code,
                    "differences": compare(baseline, shape),
                    "schemas": sorted(baseline),
                    "generate_scales": scales,
                    "seconds": round(time.time() - started, 1),
                },
                indent=1,
            )
            + "\n"
        )
    return code


if __name__ == "__main__":
    raise SystemExit(main())
