"""Shape's ``transform star|cdm`` against the baseline's, on the same retail tables (internal).

    source scripts/env.sh
    "$SHAPE_VENV/bin/python" benchmarks/vs_refengine/transform_1to1/verify.py [--scale small]

Two inputs are used, so neither tool sees only the other's data: retail generated by Shape, and
retail generated by the baseline. Each is written as Parquet and fed to both tools; the outputs
(star schema and CDM folder, as Parquet and as CSV) are compared by ``compare.py``: output schemas
(names, order, logical types) and every row. Unexplained differences exit 1; the deliberate ones
(``compare.DIFFERENCES``) are printed with their reason. Output goes to
``$BENCH_OUT_DIR/transform_1to1/``.
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parent))
from compare import DIFFERENCES, compare_cdm, compare_star, compare_star_csv  # noqa: E402
from paths import BENCH_OUT_DIR, REFENGINE_PY, SHAPE_PY  # noqa: E402

SHAPE = str(SHAPE_PY.with_name("shape"))


def _shape(*args: str) -> None:
    subprocess.run([SHAPE, *args], check=True, stdout=subprocess.DEVNULL)


def _baseline(*args: str) -> None:
    subprocess.run(
        [str(REFENGINE_PY), str(HERE / "baseline_transform.py"), *args],
        check=True,
        stderr=subprocess.DEVNULL,
    )


def _maps(out: Path) -> tuple[Path, Path]:
    from shape_domains.retail import RetailDomain

    domain = RetailDomain()
    star, cdm = out / "star_map.json", out / "cdm_map.json"
    star.write_text(json.dumps(domain.star_map()))
    cdm.write_text(json.dumps({"entities": domain.cdm_entities()}))
    return star, cdm


def run_case(label: str, source: Path, fmt: str, root: Path, maps: tuple[Path, Path]) -> list[str]:
    """Run both tools on ``source`` and compare; returns the failures."""
    case = root / f"{label}-{fmt}"
    shutil.rmtree(case, ignore_errors=True)
    _baseline("--input", str(source), "--out", str(case / "baseline"), "--format", fmt)
    _shape(
        "transform",
        "star",
        str(source),
        "--map",
        str(maps[0]),
        "-o",
        str(case / "shape/star"),
        "--format",
        fmt,
    )
    _shape(
        "transform",
        "cdm",
        str(source),
        "--map",
        str(maps[1]),
        "--model-name",
        "ShapeRetail",
        "-o",
        str(case / "shape/cdm"),
        "--format",
        fmt,
    )
    star = (compare_star if fmt == "parquet" else compare_star_csv)(
        case / "shape/star", case / "baseline/star"
    )
    cdm = compare_cdm(case / "shape/cdm", case / "baseline/cdm", fmt)
    bad = [f"{label}/{fmt} star: {line}" for line in star[0]]
    bad += [f"{label}/{fmt} cdm: {line}" for line in cdm[0]]
    tables = len(list((case / "baseline/star").glob(f"*.{fmt}")))
    print(
        f"{label} / {fmt}: {tables} star tables, {len(list((case / 'baseline/cdm').glob('*/*')))} "
        f"CDM entities compared, {len(bad)} unexplained"
    )
    for rules in (star[1], cdm[1]):
        for rule, where in rules.items():
            print(
                f"  allowed [{rule}]: {'; '.join(sorted(set(where))[:4])}"
                f"{' ...' if len(set(where)) > 4 else ''}"
            )
    return bad


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--scale", default="small")
    ap.add_argument("--seed", type=int, default=42)
    a = ap.parse_args(argv)
    root = BENCH_OUT_DIR / "transform_1to1" / a.scale
    shutil.rmtree(root, ignore_errors=True)
    root.mkdir(parents=True)
    maps = _maps(root)
    shape_in, base_in = root / "input-shape", root / "input-baseline"
    _shape(
        "generate",
        "retail",
        "--scale",
        a.scale,
        "--seed",
        str(a.seed),
        "-f",
        "parquet",
        "-o",
        str(shape_in),
    )
    _baseline(
        "--generate",
        "retail",
        "--scale",
        a.scale,
        "--seed",
        str(a.seed),
        "--input",
        str(base_in),
        "--out",
        str(root / "scratch"),
    )
    failures: list[str] = []
    for label, source in (("shape-data", shape_in), ("baseline-data", base_in)):
        for fmt in ("parquet", "csv"):
            failures += run_case(label, source, fmt, root, maps)
    print("deliberate differences:")
    for rule, reason in DIFFERENCES.items():
        print(f"  {rule}: {reason}")
    for line in failures:
        print(f"FAIL {line}")
    print("PASS" if not failures else f"{len(failures)} unexplained difference(s)")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
