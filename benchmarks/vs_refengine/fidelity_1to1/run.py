"""P4-09: the fidelity report's score against the baseline comparator, on the same pairs.

    source scripts/env.sh
    "$SHAPE_VENV/bin/python" benchmarks/vs_refengine/fidelity_1to1/run.py [--scales small,medium]

For each scale the pairs are the retail ones of ``domain_1to1`` (real = baseline seed 42):
Shape's output (seed 1042) and the baseline's own seeds 43-46, plus edge pairs built from the
baseline's seeds 42 and 43: a missing column, a missing table, an empty reference, a type
mismatch and a datetime unit mismatch. Every pair is scored twice, by the baseline's comparator in
the baseline venv (``baseline_scores.py``, ``$REFENGINE_PY``) and by ``shape.generation.report`` in
this process, and every table's two scores and their difference are reported.

Exit 0 only when every expectation holds:

* retail pairs: every table's |difference| <= 0.5 points (plan P4-09);
* ``type_mismatch``: the same bound (both kinds disagree the same way);
* ``missing_column``: the damaged table scores the baseline's score times shared/reference columns
  (within 0.5) and the missing column scores 0; every other table is within 0.5;
* ``missing_table``: the missing table scores 0 and the report fails; the others are within 0.5;
* ``empty_reference``: every table scores 0 and the report fails;
* ``unit_mismatch`` (the baseline compares raw integer counts, Shape nanoseconds): Shape's score
  equals its score for the same pair with matching units.

The report goes to ``$BENCH_OUT_DIR/fidelity_1to1/report_<scales>.{json,txt}``. Run directories are
generated by ``domain_1to1/generate.py`` when missing. The baseline checkout is only read.
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Any

import pyarrow as pa
import pyarrow.compute as pc
import pyarrow.parquet as pq

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
sys.path.insert(0, str(HERE.parent / "domain_1to1"))
import generate  # noqa: E402
from paths import BENCH_OUT_DIR, REFENGINE_PY, SHAPE_PY  # noqa: E402

DOMAIN = "retail"
REF_SEED = 42
BASELINE_SEEDS = (43, 44, 45, 46)
SHAPE_SEED = 1042
TOLERANCE = 0.5  # plan P4-09: points on the 0-100 scale
EDGE_SEED = 43
OUT = BENCH_OUT_DIR / "fidelity_1to1"


def run_dir(impl: str, scale: str, seed: int) -> Path:
    return generate.out_dir(impl, DOMAIN, scale, seed)


def ensure(impl: str, scale: str, seed: int) -> Path:
    d = run_dir(impl, scale, seed)
    if not generate.is_complete(d):
        py = REFENGINE_PY if impl == "refengine" else SHAPE_PY
        cmd = [str(py), str(HERE.parent / "domain_1to1" / "generate.py"), "--impl", impl]
        cmd += ["--domain", DOMAIN, "--scale", scale, "--seed", str(seed)]
        print(f"generating {impl} {DOMAIN}/{scale}/seed{seed}", file=sys.stderr, flush=True)
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode != 0 or not generate.is_complete(d):
            raise SystemExit(f"cannot generate {d}:\n{r.stderr[-2000:]}")
    return d


def read_dir(path: Path) -> dict[str, pa.Table]:
    return {p.stem: pq.read_table(p) for p in sorted(path.glob("*.parquet"))}


def write_dir(path: Path, tables: dict[str, pa.Table]) -> Path:
    if path.exists():
        shutil.rmtree(path)
    path.mkdir(parents=True)
    for name, t in tables.items():
        pq.write_table(t, path / f"{name}.parquet")
    return path


# --- the two comparators ----------------------------------------------------------------------


def baseline_scores(real: Path, synth: Path) -> dict[str, Any]:
    cmd = [str(REFENGINE_PY), str(HERE / "baseline_scores.py"), str(real), str(synth)]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        raise SystemExit(f"baseline comparator failed on {real} vs {synth}:\n{r.stderr[-2000:]}")
    out: dict[str, Any] = json.loads(r.stdout)
    return out


def shape_scores(real: Path, synth: Path) -> dict[str, Any]:
    from shape.generation.report import compare_tables

    out: dict[str, Any] = compare_tables(read_dir(real), read_dir(synth)).to_dict()
    return out


def compare_pair(real: Path, synth: Path) -> dict[str, Any]:
    """Both comparators on one pair: per table the two scores and their difference, and the
    largest per-column difference among the columns both score."""
    b, s = baseline_scores(real, synth), shape_scores(real, synth)
    tables: dict[str, Any] = {}
    for t, st in s["tables"].items():
        bt = b["tables"].get(t)
        row: dict[str, Any] = {"shape": st["score"], "baseline": None, "diff": None}
        if bt is not None:
            row["baseline"] = bt["score"]
            row["diff"] = st["score"] - bt["score"]
            gaps = {
                c: abs(st["columns"][c]["score"] - bc["score"])
                for c, bc in bt["columns"].items()
                if c in st["columns"] and st["columns"][c]["present"]
            }
            if gaps:
                worst = max(gaps, key=lambda k: gaps[k])
                row["max_column_diff"] = {"column": worst, "diff": gaps[worst]}
        row["missing_columns"] = st["missing_columns"]
        row["shape_columns"] = {c: v["score"] for c, v in st["columns"].items()}
        tables[t] = row
    return {
        "overall": {
            "shape": s["overall_score"],
            "baseline": b["overall_score"],
            "diff": s["overall_score"] - b["overall_score"],
        },
        "shape_passed": s["passed"],
        "shape_failures": s["failures"],
        "tables": tables,
    }


# --- pairs ------------------------------------------------------------------------------------


def retail_pairs(scale: str) -> list[tuple[str, Path, Path]]:
    real = ensure("refengine", scale, REF_SEED)
    pairs = [
        (f"shape{SHAPE_SEED}_vs_refengine{REF_SEED}", real, ensure("shape", scale, SHAPE_SEED))
    ]
    for seed in BASELINE_SEEDS:
        pairs.append(
            (f"refengine{seed}_vs_refengine{REF_SEED}", real, ensure("refengine", scale, seed))
        )
    return pairs


def edge_pairs(scale: str) -> dict[str, tuple[Path, Path, dict[str, Any]]]:
    """Edge pairs from the baseline's seeds 42 (real) and 43 (synthetic) of ``scale``."""
    real_t = read_dir(ensure("refengine", scale, REF_SEED))
    synth_t = read_dir(ensure("refengine", scale, EDGE_SEED))
    root = OUT / "edge" / scale
    out: dict[str, tuple[Path, Path, dict[str, Any]]] = {}

    def add(name: str, real: dict[str, pa.Table], synth: dict[str, pa.Table], **info: Any) -> None:
        out[name] = (
            write_dir(root / name / "real", real),
            write_dir(root / name / "synth", synth),
            info,
        )

    add("same_units", real_t, synth_t)  # reference for unit_mismatch
    dropped = {**synth_t, "customer": synth_t["customer"].drop_columns(["email"])}
    add("missing_column", real_t, dropped, table="customer", column="email")
    add(
        "missing_table",
        real_t,
        {k: v for k, v in synth_t.items() if k != "return"},
        table="return",
    )
    add("empty_reference", {k: v.slice(0, 0) for k, v in real_t.items()}, synth_t)
    o = synth_t["order"]
    ol = synth_t["order_line"]
    mism = {
        **synth_t,
        "order": o.set_column(  # a timestamp column as ISO text
            o.schema.get_field_index("order_date"),
            "order_date",
            pc.strftime(o["order_date"], "%Y-%m-%dT%H:%M:%S"),
        ),
        "order_line": ol.set_column(  # a numeric column as text of a different kind
            ol.schema.get_field_index("discount_percent"),
            "discount_percent",
            pc.binary_join_element_wise(
                pa.scalar("v", pa.large_string()),
                pc.cast(ol["discount_percent"], pa.large_string()),
                pa.scalar("", pa.large_string()),
            ),
        ),
    }
    add("type_mismatch", real_t, mism)
    ns_cols = {f.name for f in o.schema if pa.types.is_timestamp(f.type) and f.type.unit == "us"}
    unit = {
        **synth_t,
        "order": o.cast(
            pa.schema(
                [pa.field(f.name, pa.timestamp("ns")) if f.name in ns_cols else f for f in o.schema]
            )
        ),
    }
    add("unit_mismatch", real_t, unit)
    return out


# --- expectations -----------------------------------------------------------------------------


def judge_equivalent(res: dict[str, Any]) -> list[str]:
    bad = []
    for t, r in res["tables"].items():
        if r["diff"] is None:
            bad.append(f"{t}: the baseline did not score it")
        elif abs(r["diff"]) > TOLERANCE:
            bad.append(f"{t}: |diff| {abs(r['diff']):.4f} > {TOLERANCE}")
    return bad


def judge_edge(
    name: str, info: dict[str, Any], res: dict[str, Any], same: dict[str, Any]
) -> list[str]:
    bad: list[str] = []
    tables = res["tables"]
    if name == "type_mismatch":
        return judge_equivalent(res)
    if name == "missing_column":
        for t, r in tables.items():
            if t != info["table"]:
                bad += [f"{t}: {x}" for x in judge_equivalent({"tables": {t: r}})]
                continue
            n_ref = len(r["shape_columns"])
            expect = r["baseline"] * (n_ref - 1) / n_ref
            if abs(r["shape"] - expect) > TOLERANCE:
                bad.append(
                    f"{t}: shape {r['shape']:.3f} != baseline * shared/reference {expect:.3f}"
                )
            if (
                r["shape_columns"][info["column"]] != 0.0
                or info["column"] not in r["missing_columns"]
            ):
                bad.append(f"{t}.{info['column']}: a missing column must score 0")
    elif name == "missing_table":
        miss = tables[info["table"]]
        if miss["shape"] != 0.0 or miss["baseline"] is not None:
            bad.append(f"{info['table']}: a missing table must score 0 (baseline: not scored)")
        if res["shape_passed"]:
            bad.append("a missing table must fail the report")
        for t, r in tables.items():
            if t != info["table"]:
                bad += [f"{t}: {x}" for x in judge_equivalent({"tables": {t: r}})]
    elif name == "empty_reference":
        bad += [f"{t}: scores {r['shape']}, not 0" for t, r in tables.items() if r["shape"] != 0.0]
        if res["shape_passed"]:
            bad.append("an empty reference must fail")
    elif name == "unit_mismatch":
        for t, r in tables.items():
            if abs(r["shape"] - same["tables"][t]["shape"]) > 1e-9:
                bad.append(f"{t}: shape differs from the matching-units score")
    return bad


def cli_checks(pairs: list[tuple[str, Path, Path]], empty: tuple[Path, Path]) -> dict[str, Any]:
    """The ``shape fidelity`` command: exit codes, the three report formats, and the alias."""
    out: dict[str, Any] = {}
    shape = str(Path(SHAPE_PY).parent / "shape")
    name, real, synth = pairs[0]
    rep = OUT / "cli"
    rep.mkdir(parents=True, exist_ok=True)
    cmd = [shape, "fidelity", str(real), str(synth)]  # the default pass marks
    for ext in ("json", "md", "html"):
        cmd += ["-o", str(rep / f"{name}.{ext}")]
    r = subprocess.run(cmd, capture_output=True, text=True)
    out["retail_exit"] = r.returncode
    out["files"] = {e: (rep / f"{name}.{e}").stat().st_size for e in ("json", "md", "html")}
    j = json.loads((rep / f"{name}.json").read_text())
    out["json_overall"] = j["overall_score"]
    alias = subprocess.run(
        [shape, "compare", str(real), str(synth)], capture_output=True, text=True
    )
    out["alias_exit"] = alias.returncode
    low = subprocess.run(
        [shape, "fidelity", str(real), str(synth), "--min-score", "100"],
        capture_output=True,
        text=True,
    )
    out["threshold_100_exit"] = low.returncode
    emp = subprocess.run([shape, "fidelity", str(empty[0]), str(empty[1])], capture_output=True)
    out["empty_reference_exit"] = emp.returncode
    out["ok"] = (
        out["retail_exit"] == 0
        and out["alias_exit"] == 0
        and out["threshold_100_exit"] == 1
        and out["empty_reference_exit"] == 1
        and all(v > 0 for v in out["files"].values())
    )
    return out


def text_report(result: dict[str, Any]) -> str:
    lines = []
    for scale, sc in result["scales"].items():
        for name, res in {**sc["retail"], **sc["edge"]}.items():
            lines.append(
                f"== {scale} / {name}   overall shape {res['overall']['shape']:.2f} "
                f"baseline {res['overall']['baseline']:.2f} diff {res['overall']['diff']:+.4f}"
            )
            for t, r in res["tables"].items():
                base = "   n/a  " if r["baseline"] is None else f"{r['baseline']:8.3f}"
                diff = "   n/a" if r["diff"] is None else f"{r['diff']:+9.5f}"
                col = r.get("max_column_diff")
                worst = f"  worst column {col['column']} {col['diff']:.5f}" if col else ""
                lines.append(
                    f"   {t:<18} baseline {base}  shape {r['shape']:8.3f}  diff {diff}{worst}"
                )
            for x in sc["failures"].get(name, []):
                lines.append(f"   FAIL {x}")
    lines.append(f"cli: {json.dumps(result['cli'])}")
    lines.append(f"max |table diff| over retail pairs: {result['max_retail_table_diff']:.5f}")
    lines.append("RESULT: " + ("PASS" if result["passed"] else "FAIL"))
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--scales", default="small,medium")
    ap.add_argument(
        "--out", help="report path (default: $BENCH_OUT_DIR/fidelity_1to1/report_*.json)"
    )
    a = ap.parse_args(argv)
    scales = a.scales.split(",")
    result: dict[str, Any] = {"domain": DOMAIN, "tolerance": TOLERANCE, "scales": {}}
    ok = True
    worst = 0.0
    cli_pairs: list[tuple[str, Path, Path]] = []
    empty: tuple[Path, Path] | None = None
    for scale in scales:
        sc: dict[str, Any] = {"retail": {}, "edge": {}, "failures": {}}
        pairs = retail_pairs(scale)
        cli_pairs = cli_pairs or pairs
        for name, real, synth in pairs:
            res = sc["retail"][name] = compare_pair(real, synth)
            bad = judge_equivalent(res)
            worst = max([worst] + [abs(r["diff"]) for r in res["tables"].values()])
            if bad:
                sc["failures"][name] = bad
        edges = edge_pairs(scale)
        results = {n: compare_pair(r, s) for n, (r, s, _) in edges.items()}
        for n, (_r, _s, info) in edges.items():
            sc["edge"][n] = results[n]
            if n == "same_units":
                continue
            bad = judge_edge(n, info, results[n], results["same_units"])
            if bad:
                sc["failures"][n] = bad
        empty = empty or edges["empty_reference"][:2]
        ok = ok and not sc["failures"]
        result["scales"][scale] = sc
    assert empty is not None
    result["cli"] = cli_checks(cli_pairs, empty)
    result["max_retail_table_diff"] = worst
    result["passed"] = bool(ok and result["cli"]["ok"])
    OUT.mkdir(parents=True, exist_ok=True)
    path = Path(a.out) if a.out else OUT / f"report_{'_'.join(scales)}.json"
    path.write_text(json.dumps(result, indent=1, default=str))
    txt = text_report(result)
    path.with_suffix(".txt").write_text(txt)
    sys.stdout.write(txt)
    return 0 if result["passed"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
